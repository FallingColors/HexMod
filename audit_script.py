import os
import re

mishap_dir = r"D:\GEMINI AGY\workspaces\HexMod_tooling\Common\src\main\java\at\petrak\hexcasting\api\casting\mishaps"
lang_path = r"D:\GEMINI AGY\workspaces\HexMod_tooling\Common\src\main\resources\assets\hexcasting\lang\en_us.flatten.json5"

keys_found = set()
for root, dirs, files in os.walk(mishap_dir):
    for f in files:
        if f.endswith(".kt"):
            path = os.path.join(root, f)
            text = open(path, "r", encoding="utf-8").read()
            matches = re.findall(r'error\s*\(\s*\"([^\"]+)\"', text)
            for m in matches:
                keys_found.add(m)

lang_text = open(lang_path, "r", encoding="utf-8").read()

audit_lines = ["# Mishap Localization Audit Report\n", "Generated by automated diagnostic script.\n\n"]
audit_lines.append("| Mishap Error Key | Present in en_us.flatten.json5 | Status |\n")
audit_lines.append("|---|---|---|\n")

missing_count = 0
for key in sorted(keys_found):
    present = key in lang_text
    status = "OK" if present else "MISSING"
    if not present:
        missing_count += 1
    audit_lines.append(f"| `{key}` | {present} | {status} |\n")

audit_lines.insert(2, f"Total mishap error keys checked: {len(keys_found)}\n")
audit_lines.insert(3, f"Missing keys: {missing_count}\n\n")

output_path = r"D:\GEMINI AGY\workspaces\HexMod_tooling\MISHAP_LOCALIZATION_AUDIT.md"
open(output_path, "w", encoding="utf-8").writelines(audit_lines)
print(f"Audit report written to {output_path}. Missing keys: {missing_count}")
